# 尝试设计一个"分层规划"系统:先生成高层次的抽象计划，然后针对每个高层步骤再生成详细的子计划。这种设计有什么优势？
# 设计:
# 第一层(高层计划):只给出抽象目标,例如 ["确定行程时间与预算", "预订往返机票", "预订酒店", "安排地面交通", "汇总行程单"]。
# 第二层(子计划):对每个高层步骤再调用一次规划器,生成详细步骤。例如"预订往返机票"可展开为"查询可选航班 → 对比价格与时间 → 确认并下单 → 记录订单号"。
# 执行时按高层步骤顺序处理,每个高层步骤内部再按子计划执行。
# 优势:
# 降低单次规划难度:复杂任务一次规划容易遗漏或出错,拆成两层后每次只需处理一个粒度。
# 便于局部重规划:某个子步骤失败,只需要重做对应的子计划,不影响高层计划和其他已完成部分,重规划成本更小。
# 上下文更精简:执行某个子计划时,只需要该高层步骤的信息,不用带上整个大计划,节省 token。
# 可读性和可控性更好:高层计划便于用户审阅和确认,也方便在关键节点做人工介入。
# 便于并行和分工:互不依赖的高层步骤可以并行,不同子计划可以交给不同的专业子智能体。
# 代价:规划次数增多,调用次数和延迟增加;层级之间需要保持一致,高层计划出错会放大到所有子计划。所以层级不宜过深,通常两层就够。



